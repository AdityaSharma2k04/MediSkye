import React from 'react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { stripAbnormalFlags } from './ChatMessage';

/**
 * PrintableTranscript — print-only, formal full-chat export.
 *
 * Rendered hidden on screen (see index.css) and revealed only during
 * window.print(), reusing the same print pipeline as PrintableSummary.
 * Contains the complete conversation, the lab metrics table, and the
 * mandatory medical disclaimer.
 */
export default function PrintableTranscript({ document: doc, messages = [], metrics = [], user }) {
  const patientName = user?.full_name || user?.email || 'Not specified';
  const docTitle = doc?.title || doc?.filename || 'General consultation';
  const generatedAt = new Date().toLocaleString([], {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  const cleanedMetrics = (Array.isArray(metrics) ? metrics : []).map((m) => ({
    test: m.test || m.name || '—',
    value: m.value ?? '—',
    unit: m.unit || '—',
    range: m.range || m.reference_range || '—',
    status: m.status || 'Normal',
  }));

  return (
    <div id="print-transcript">
      {/* Header */}
      <div className="ts-header">
        <div className="ts-logo">MediSkye AI</div>
        <div className="ts-subtitle">Consultation Transcript &amp; Lab Data Export</div>
      </div>

      <div className="ts-meta">
        <div><strong>Report:</strong> {docTitle}</div>
        <div><strong>Patient:</strong> {patientName}</div>
        <div><strong>Exported:</strong> {generatedAt}</div>
      </div>

      {/* Conversation transcript */}
      <h3 className="ts-section-title">Conversation</h3>
      {messages.length === 0 ? (
        <p className="ts-empty">No conversation messages were recorded for this report.</p>
      ) : (
        messages.map((m, idx) => {
          const isUser = m.sender === 'user' || m.role === 'user';
          const text = stripAbnormalFlags(m.text || m.message || '');
          return (
            <div key={m.id || idx} className={`ts-msg ${isUser ? 'ts-msg-user' : 'ts-msg-ai'}`}>
              <div className="ts-msg-meta">{isUser ? 'You' : 'MediSkye AI'}{m.timestamp ? ` · ${m.timestamp}` : ''}</div>
              <div className="ts-msg-body"><ReactMarkdown remarkPlugins={[remarkGfm]}>{text}</ReactMarkdown></div>
            </div>
          );
        })
      )}

      {/* Lab metrics */}
      <h3 className="ts-section-title">Lab Metrics</h3>
      {cleanedMetrics.length === 0 ? (
        <p className="ts-empty">No structured lab values were extracted for this report.</p>
      ) : (
        <table className="ts-table">
          <thead>
            <tr>
              <th>Test Name</th>
              <th>Value</th>
              <th>Unit</th>
              <th>Reference Range</th>
              <th>Status</th>
            </tr>
          </thead>
          <tbody>
            {cleanedMetrics.map((m, i) => (
              <tr key={i}>
                <td>{m.test}</td>
                <td>{m.value}</td>
                <td>{m.unit}</td>
                <td>{m.range}</td>
                <td>{m.status}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}

      {/* Disclaimer footer */}
      <div className="print-footer">
        <p>
          MediSkye AI provides educational information only. It is not a substitute for professional
          medical advice, diagnosis, or treatment. Always consult a qualified healthcare provider with
          questions about a medical condition. In an emergency, call your local emergency number immediately.
        </p>
        <p className="ts-generated">Generated by MediSkye AI · {generatedAt}</p>
      </div>
    </div>
  );
}
